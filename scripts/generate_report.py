"""
MediTwin AI — PDF Report Generator
"""
import json
from pathlib import Path
from datetime import datetime
from typing import Dict, Any

def generate_pdf(report: Dict[str, Any], patient_id: str) -> Path:
    """Generate a PDF clinical report using fpdf2."""
    from fpdf import FPDF

    out_dir = Path("outputs/reports")
    out_dir.mkdir(parents=True, exist_ok=True)
    pdf_path = out_dir / f"MediTwin_{patient_id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Header
    pdf.set_fill_color(10, 25, 47)
    pdf.rect(0, 0, 210, 40, "F")
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(79, 134, 247)
    pdf.cell(0, 15, "MediTwin AI", ln=True, align="C")
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(150, 180, 200)
    pdf.cell(0, 8, "Multimodal Multi-Agent Clinical Decision Support System", ln=True, align="C")
    pdf.cell(0, 8, f"Patient ID: {patient_id}  |  {datetime.now().strftime('%d %b %Y %H:%M')}", ln=True, align="C")
    pdf.ln(15)

    # Reset colors
    pdf.set_text_color(20, 20, 20)

    def section(title: str):
        pdf.set_font("Helvetica", "B", 13)
        pdf.set_fill_color(230, 240, 255)
        pdf.set_text_color(10, 40, 100)
        pdf.cell(0, 9, title, ln=True, fill=True)
        pdf.set_text_color(20, 20, 20)
        pdf.ln(2)

    def body(text: str, size: int = 10):
        pdf.set_font("Helvetica", "", size)
        pdf.multi_cell(0, 6, text)
        pdf.ln(2)

    # Summary
    section("Clinical Summary")
    body(report.get("summary", "N/A"))

    # Imaging
    imaging = report.get("imaging_result", {})
    section("Imaging Analysis (Chest X-Ray)")
    body(f"Prediction: {imaging.get('prediction', 'N/A')}")
    body(f"Confidence: {imaging.get('confidence', 0):.1%}")

    # Lab
    lab = report.get("lab_result", {})
    section("Laboratory / Cardiac Risk Assessment")
    body(f"Prediction: {lab.get('prediction', 'N/A')}")
    body(f"Confidence: {lab.get('confidence', 0):.1%}")
    if lab.get("top_risk_factors"):
        body("Top Risk Factors (SHAP):")
        for feat, val in lab["top_risk_factors"][:5]:
            body(f"  • {feat}: {val:+.4f}")

    # Differentials
    section("Differential Diagnosis")
    for d in report.get("differential_diagnosis", []):
        body(f"[{d.get('likelihood','N/A')}] {d.get('diagnosis','N/A')}: {d.get('basis','')}")

    # Recommendations
    section("Treatment Recommendations")
    for i, r in enumerate(report.get("recommendations", []), 1):
        body(f"{i}. {r}")

    # Evidence
    section("Evidence Citations (RAG)")
    for ev in report.get("evidence_citations", [])[:3]:
        body(f"[{ev['rank']}] {ev['title']}")
        body(f"    Source: {ev['source']}")
        body(f"    {ev['snippet'][:200]}...")
        pdf.ln(2)

    # Disclaimer
    pdf.ln(5)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(120, 120, 120)
    pdf.multi_cell(0, 5,
        "DISCLAIMER: This report is AI-generated by MediTwin AI for academic/research purposes only. "
        "All findings must be verified by a licensed healthcare professional before clinical use. "
        "MediTwin AI is not a certified medical device.")

    pdf.output(str(pdf_path))
    return pdf_path
